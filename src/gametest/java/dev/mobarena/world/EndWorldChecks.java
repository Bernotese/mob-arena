package dev.mobarena.world;

import dev.mobarena.core.GameContext;
import dev.mobarena.team.TeamId;
import net.minecraft.core.BlockPos;
import net.minecraft.gametest.framework.GameTestHelper;
import net.minecraft.server.level.ServerPlayer;
import net.minecraft.world.entity.EntityTypes;
import net.minecraft.world.level.block.Blocks;
import net.minecraft.world.level.block.entity.TheEndGatewayBlockEntity;
import net.minecraft.world.level.portal.TeleportTransition;
import net.minecraft.world.phys.*;

final class EndWorldChecks {
    private EndWorldChecks() {}
    static void verify(GameTestHelper h, GameContext ctx, ServerPlayer red, ServerPlayer blue, Runnable next) {
        var worlds = ctx.get(TeamWorlds.KEY);
        for (var player : new ServerPlayer[]{red, blue}) {
            var handle = worlds.get(ctx.team(player.getUUID())).end();
            handle.setTickWhenEmpty(true);
            var end = handle.asLevel();
            player.teleport(new TeleportTransition(end, new Vec3(0.5, 80, 0.5), Vec3.ZERO, 0, 0, TeleportTransition.DO_NOTHING));
            player.getAbilities().invulnerable = true;
            player.onUpdateAbilities();
            for (int x = -8; x <= 8; x++) for (int z = -8; z <= 8; z++) {
                end.getChunk(x, z);
            }
        }
        h.runAfterDelay(220, () -> {
            var redEnd = worlds.get(TeamId.RED).end().asLevel();
            var blueEnd = worlds.get(TeamId.BLUE).end().asLevel();
            var box = new AABB(-256, -64, -256, 256, 512, 256);
            var redDragons = redEnd.getEntitiesOfClass(net.minecraft.world.entity.boss.enderdragon.EnderDragon.class, box);
            var blueDragons = blueEnd.getEntitiesOfClass(net.minecraft.world.entity.boss.enderdragon.EnderDragon.class, box);
            h.assertValueEqual(redDragons.size(), 1, "W14 RED has one dragon");
            h.assertValueEqual(blueDragons.size(), 1, "W14 BLUE has one dragon");
            redDragons.getFirst().kill(redEnd);
            h.assertTrue(redEnd.getDragonFight().hasPreviouslyKilledDragon(), "W14 RED fight records death");
            h.assertFalse(blueEnd.getDragonFight().hasPreviouslyKilledDragon(), "W14 BLUE fight remains alive");
            boolean portal = false;
            for (int y = redEnd.getMinY(); y < redEnd.getMaxY(); y++) for (int x = -4; x <= 4; x++) for (int z = -4; z <= 4; z++) {
                portal |= redEnd.getBlockState(new BlockPos(x, y, z)).is(Blocks.END_PORTAL);
            }
            h.assertTrue(portal, "W14 RED exit portal exists");
            // W17: use the gateway generated by the fight, not a synthetic exit position.
            TheEndGatewayBlockEntity gateway = null;
            for (int x = -7; x <= 7 && gateway == null; x++) for (int z = -7; z <= 7 && gateway == null; z++) {
                for (var blockEntity : redEnd.getChunk(x, z).getBlockEntities().values()) {
                    if (blockEntity instanceof TheEndGatewayBlockEntity found) { gateway = found; break; }
                }
            }
            h.assertTrue(gateway != null, "W17 fight creates a gateway");
            var position = gateway.getPortalPosition(redEnd, gateway.getBlockPos());
            h.assertTrue(position != null && position.horizontalDistance() > 700, "W17 gateway finds outer islands");
            red.teleport(new TeleportTransition(redEnd, position, Vec3.ZERO, 0, 0, TeleportTransition.DO_NOTHING));
            h.assertTrue(red.level() == redEnd && red.position().horizontalDistance() > 700, "W17 player remains in own End");
            next.run();
        });
    }
}
